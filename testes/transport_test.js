const assert=require('node:assert/strict');
const vm=require('node:vm');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const T=require('../aplicativo/web/transport.js');
const input='https://api.us-e1.tago.io/data?variable%5B%5D=nivel&qty=500&start_date=2026-11-24T12%3A00%3A00.000Z';
const date=Date.UTC(2026,10,25,12);
const raw=T.nativeUrl(input,date);
assert(!raw.includes('%')&&!raw.includes('#'));
assert.equal(new URL(raw).searchParams.get('variable[]'),'nivel');
assert.equal(T.canonical(raw),T.canonical(raw.replaceAll('[','%5B').replaceAll(']','%5D')));
assert.equal(T.canonical(raw),T.canonical(raw.replaceAll('[','%255B').replaceAll(']','%255D')));
assert.throws(()=>T.nativeUrl('http://example.com/data',date));

async function main(){
  // Execute callbacks generated by the actual BKY, including apostrophes,
  // backslashes and pretty-printed JSON, against the real JavaScript bridge.
  const fixture=JSON.parse(execFileSync('python',[path.join(__dirname,'aia_bridge_test.py'),'--fixture'],{encoding:'utf8'}));
  let sent;const actual=T.create({now:()=>fixture.time,getBridge:()=>({setWebViewString:v=>sent=JSON.parse(v)})});
  const waiting=actual.request(fixture.original,'TOKEN_FICTICIO');
  assert.equal(sent[0],fixture.request);
  const sandbox={window:{EcoTransport:actual}};
  fixture.scripts.forEach(script=>vm.runInNewContext(script,sandbox));
  const result=await waiting;
  assert.equal(result.result[0].value,35);
  assert.equal(result.result[0].metadata.note,"Patio d'Agua\nSala \\ B");

  let next,old;
  const native=T.create({now:()=>date,getBridge:()=>({setWebViewString:v=>{next=JSON.parse(v)[0];}})});
  let promise=native.request(input,'TOKEN_A');old=next;
  native.receive([next,401,'{"status":false}']);
  await assert.rejects(promise,/HTTP 401/);
  promise=native.request(input,'TOKEN_B');assert.notEqual(next,old);
  native.receive([old,200,'{"status":true,"result":[{"value":99}]}']);
  native.receive([next,200,'{"status":true,"result":[{"value":35}]}']);
  assert.equal((await promise).result[0].value,35);
  promise=native.request(input,'TOKEN_C');native.receive([next,200,'not json']);
  await assert.rejects(promise,/invalido/);

  let timeout,requestUrl;
  const timed=T.create({now:()=>date,setTimer:fn=>{timeout=fn;return 1;},clearTimer:()=>{},getBridge:()=>({setWebViewString:v=>{requestUrl=JSON.parse(v)[0];}})});
  promise=timed.request(input,'TOKEN');const blocked=assert.rejects(promise,/Companion nao confirmou/);timeout();await blocked;
  promise=timed.request(input,'TOKEN');timed.ack([requestUrl]);const started=assert.rejects(promise,/consulta foi iniciada/);timeout();await started;
  console.log('PASS: resposta BKY real serializada, modelo de URL iOS, aspas e quebras de linha, HTTP 401, respostas atrasadas e diagnosticos de timeout');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
